export function translateTree(treeStr, lang = 'ta') {
  if (!treeStr) return lang === 'ta' ? 'அரச மரம்' : 'Sacred Peepal';
  const str = String(treeStr).trim();
  for (const [k, obj] of Object.entries(TREES_MAP)) {
    if (str.includes(k) || str.toLowerCase().includes(obj.en.toLowerCase())) {
      return obj[lang] || obj.en;
    }
  }
  return str;
}

export function translateVaara(vaaraStr, lang = 'ta') {
  if (!vaaraStr) return lang === 'ta' ? 'வெள்ளிக்கிழமை' : 'Friday';
  const s = String(vaaraStr).toLowerCase().trim();
  for (const [k, obj] of Object.entries(VAARA_MAP)) {
    if (s.includes(k) || s.includes(obj.en.toLowerCase()) || s.includes(obj.ta)) {
      return obj[lang] || obj.en;
    }
  }
  return vaaraStr;
}

export function translatePaksha(pakshaStr, lang = 'ta') {
  if (!pakshaStr) return lang === 'ta' ? 'கிருஷ்ண பக்ஷம் (தேய்பிறை)' : 'Krishna Paksha';
  const s = String(pakshaStr).toLowerCase().trim();
  if (s.includes('shukla') || s.includes('வளர்')) {
    return PAKSHA_MAP.shukla[lang] || PAKSHA_MAP.shukla.en;
  }
  return PAKSHA_MAP.krishna[lang] || PAKSHA_MAP.krishna.en;
}

export function translateRitu(rituStr, lang = 'ta') {
  if (!rituStr) return RITU_MAP.sharad[lang] || RITU_MAP.sharad.en;
  const s = String(rituStr).toLowerCase().trim();
  for (const [k, obj] of Object.entries(RITU_MAP)) {
    if (s.includes(k)) return obj[lang] || obj.en;
  }
  return RITU_MAP.sharad[lang] || RITU_MAP.sharad.en;
}
