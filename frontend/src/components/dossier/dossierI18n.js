// Helper: Format Dasha Balance in the target language
export function formatLocalizedDashaBalance(b, lang = 'en') {
  const t = DOSSIER_TRANSLATIONS[lang] || DOSSIER_TRANSLATIONS.en;
  if (!b) {
    const defaultLord = PLANET_MAP.rahu[lang] || 'Rahu';
    return `${defaultLord} - 16 ${t.years} 06 ${t.months} 03 ${t.days}`;
  }
  if (typeof b === 'object') {
    const lord = translatePlanet(b.lord || 'Rahu', lang);
    const y = b.years !== undefined ? b.years : 16;
    const m = b.months !== undefined ? b.months : 6;
    const d = b.days !== undefined ? b.days : 3;
    if (lang === 'ta') {
      return `${lord} திசையில் ${y} வருடம் ${m} மாதம் ${d} நாள்`;
    } else if (lang === 'kn') {
      return `${lord} ದಶೆಯಲ್ಲಿ ${y} ವರ್ಷ ${m} ತಿಂಗಳು ${d} ದಿನ`;
    } else if (lang === 'hi') {
      return `${lord} दशा में ${y} वर्ष ${m} माह ${d} दिन`;
    } else if (lang === 'te') {
      return `${lord} దశలో ${y} సంవత్సరాలు ${m} నెలలు ${d} రోజులు`;
    }
    return `${lord} Dasha: ${y} ${t.years} ${m} ${t.months} ${d} ${t.days}`;
  }
  return String(b);
}


