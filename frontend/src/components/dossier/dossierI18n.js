    'sa': 'saturn',
    'sat': 'saturn',
    'saturn': 'saturn',
    'ra': 'rahu',
    'rah': 'rahu',
    'rahu': 'rahu',
    'ke': 'ketu',
    'ket': 'ketu',
    'ketu': 'ketu',
    'la': 'lagna',
