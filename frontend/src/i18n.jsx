const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem('astrojit_lang') || 'en');

  const setLanguage = (newLang) => {
    localStorage.setItem('astrojit_lang', newLang);
    setLang(newLang);
  };

  // Helper factory that supports both t('key') and t.key
  const createT = (currentLang) => {
    const fn = (key, fallback) => {
      if (!key) return '';
      return translations[currentLang]?.[key] ?? translations['en']?.[key] ?? fallback ?? key;
    };
    return new Proxy(fn, {
      get(target, prop) {
        if (typeof prop === 'string') {
          if (prop in target) return target[prop];
          return translations[currentLang]?.[prop] ?? translations['en']?.[prop] ?? prop;
        }
        return target[prop];
      },
    });
  };

  const t = createT(lang);

  return (
    <LanguageContext.Provider value={{ lang, setLanguage, t, LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLang() {
  return useContext(LanguageContext);
}
