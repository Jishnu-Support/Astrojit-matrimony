    if (lang === 'ta') return 'செவ்வாய் தோஷ நிவர்த்தி';
    if (lang === 'kn') return 'ಕುಜ ದೋಷ ನಿವಾರಣೆ';
    if (lang === 'hi') return 'मंगल दोष निवारण';
