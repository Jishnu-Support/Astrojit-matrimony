export function formatNakshatra(raw, lang) {
  if (!raw) return '';
  const clean = raw.replace(/\s*\([\u0B80-\u0BFF\s]+\)/g, '').trim();
  for (const [key, map] of Object.entries(NAKSHATRA_MAP)) {
    if (clean.toLowerCase().includes(key.toLowerCase())) {
      return map[lang] || map.en || key;
    }
  }
  return clean;
}

